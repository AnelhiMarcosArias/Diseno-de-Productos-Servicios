-- Additive table for the separate synthetic V1-V12 demonstration flow.
-- Existing case, questionnaire, evaluation and result data are not changed.
CREATE TABLE IF NOT EXISTS resultado_simulacion (
    id_evaluacion BIGINT PRIMARY KEY,
    respuestas JSONB NOT NULL,
    estado VARCHAR(24) NOT NULL,
    indice_experimental NUMERIC(5,2),
    modelo_version VARCHAR(100),
    fecha_generacion TIMESTAMP,
    codigo_error VARCHAR(40),
    CONSTRAINT ck_resultado_simulacion_indice CHECK (
        indice_experimental IS NULL OR (indice_experimental >= 0 AND indice_experimental <= 100)
    )
);

-- On existing installations the referenced table is present. On a clean
-- installation Flyway runs before Hibernate creates the legacy tables; the
-- JPA mapping adds the same FK after those tables exist.
DO $$
BEGIN
    IF to_regclass('evaluacion') IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_simulacion_evaluacion') THEN
        ALTER TABLE resultado_simulacion
            ADD CONSTRAINT fk_simulacion_evaluacion
            FOREIGN KEY (id_evaluacion) REFERENCES evaluacion(id_evaluacion);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS auditoria (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT,
    accion VARCHAR(60) NOT NULL,
    recurso VARCHAR(60) NOT NULL,
    referencia VARCHAR(100),
    fecha_evento TIMESTAMP NOT NULL
);

DO $$
BEGIN
    IF to_regclass('usuario') IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_auditoria_usuario') THEN
        ALTER TABLE auditoria ADD CONSTRAINT fk_auditoria_usuario
            FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario);
    END IF;
END $$;
