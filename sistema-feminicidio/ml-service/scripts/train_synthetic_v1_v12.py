"""Train a reproducible academic-only XGBoost demo for the product questionnaire.

The labels are generated by the documented toy rule in docs/synthetic_model.md.
They are not observed outcomes and have no clinical or predictive validity.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
from xgboost import XGBClassifier

MODEL_VERSION = "synthetic-v1-v12-xgb-demo-v1"
SEED = 20261117
FEATURES = [f"V{i}" for i in range(1, 13)]
ARTIFACTS = Path(__file__).resolve().parents[1] / "artifacts"


def generate_dataset(rows: int = 12_000, seed: int = SEED) -> tuple[np.ndarray, np.ndarray]:
    """Generate categorical answers: 0=NO, 1=SI, 2=NO_ESTOY_SEGURA."""
    rng = np.random.default_rng(seed)
    x = rng.choice(np.array([0, 1, 2], dtype=np.int8), size=(rows, 12), p=[0.48, 0.38, 0.14])
    # Explicitly synthetic demonstration rule; equal contributions avoid asserting
    # domain-specific weighting. Uncertainty is visible and contributes partially.
    demo_score = np.sum((x == 1).astype(np.float32), axis=1) + 0.35 * np.sum((x == 2).astype(np.float32), axis=1)
    y = (demo_score >= 4.5).astype(np.int8)
    return x, y


def train(output_dir: Path = ARTIFACTS) -> dict[str, object]:
    x, y = generate_dataset()
    model = XGBClassifier(
        n_estimators=180,
        max_depth=3,
        learning_rate=0.06,
        subsample=0.9,
        colsample_bytree=1.0,
        objective="binary:logistic",
        eval_metric="logloss",
        random_state=SEED,
        n_jobs=2,
    )
    model.fit(x, y)
    output_dir.mkdir(parents=True, exist_ok=True)
    artifact_path = output_dir / f"{MODEL_VERSION}.json"
    model.save_model(artifact_path)
    digest = hashlib.sha256(artifact_path.read_bytes()).hexdigest()
    metadata = {
        "model_version": MODEL_VERSION,
        "model_type": "synthetic_academic_demonstration",
        "algorithm": "XGBoost",
        "feature_names": FEATURES,
        "encoding": {"NO": 0, "SI": 1, "NO_ESTOY_SEGURA": 2},
        "training_rows": int(len(x)),
        "random_seed": SEED,
        "label_rule": "count(SI) + 0.35*count(NO_ESTOY_SEGURA) >= 4.5",
        "artifact_file": artifact_path.name,
        "artifact_sha256": digest,
        "predicts_femicide": False,
        "clinical_validity": False,
    }
    metadata_path = output_dir / f"{MODEL_VERSION}.metadata.json"
    metadata_path.write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    return metadata


if __name__ == "__main__":
    result = train()
    print(f"Generated synthetic demo model {result['model_version']} ({result['training_rows']} synthetic rows).")
    print("This artifact is not clinically valid and does not predict real-world femicide or future violence.")
